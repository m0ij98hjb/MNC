// Run: node scripts/gen-admin-theme.js
// Generates src/app/admin/admin-theme.css — light, site-identity theme for the dashboard.
const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, '..', 'src', 'app', 'admin', 'admin-theme.css');

const S = '.admin-shell';
const tok = (c) => `[class~="${c}"]`;

// Solid coloured fills whose text must stay white (buttons, badges, avatars)
const hues = ['red', 'rose', 'pink', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia'];
const solidFills = [];
for (const h of hues) for (const n of [500, 600, 700, 800, 900]) solidFills.push(tok(`bg-${h}-${n}`));

const solid = solidFills.join(', ');
// Elements that keep their original (dark) look
const KEEP = `.keep-dark, .keep-dark *`;

// Dark surfaces → white
const darkHex = ['#000', '#000000', '#111', '#111118', '#0a0e17', '#0d1117', '#0e0d0a', '#0d0d14', '#0a0a0a', '#0b0e12', '#05090d', '#0b1320', '#0a0a14', '#060E1A', '#04090F', '#1a1a1a', '#222', '#0f172a'];
const darkCls = darkHex.map((h) => tok(`bg-[${h}]`)).concat(['.bg-black', '.bg-slate-700', '.bg-slate-800', '.bg-slate-900', '.bg-slate-950', '.bg-gray-800', '.bg-gray-900', '.bg-gray-950', '.bg-neutral-900', '.bg-neutral-950', '.bg-zinc-800', '.bg-zinc-900', '.bg-zinc-950'].map((c) => tok(c.slice(1))));
const darkRgb = ['rgb(0, 0, 0)', 'rgb(10, 14, 23)', 'rgb(11, 19, 32)', 'rgb(10, 10, 10)', 'rgb(17, 17, 17)', 'rgb(13, 17, 23)', 'rgba(5, 5, 8, 0.97)', 'rgb(5, 9, 13)', 'rgb(15, 23, 42)'];
const darkInline = darkRgb.flatMap((c) => [`[style*="background: ${c}"]`, `[style*="background-color: ${c}"]`]);

// Text tiers (same scale as the public site)
const tiers = [
  ['#0f172a', ['text-white', 'text-white/90', 'text-white/85']],
  ['#334155', ['text-white/80', 'text-white/75', 'text-white/70']],
  ['#475569', ['text-white/65', 'text-white/60', 'text-white/55']],
  ['#64748b', ['text-white/50', 'text-white/45', 'text-white/42', 'text-white/40', 'text-white/38', 'text-white/35']],
  ['#7d8da3', ['text-white/30', 'text-white/28', 'text-white/25', 'text-white/20']],
  ['#cbd5e1', ['text-white/15', 'text-white/10', 'text-white/0']],
];

// Gold text → logo orange
const goldText = ['#c8a96e', '#C9A34D', '#D5B25D', '#E1BF67', '#dcbb7d', '#B8923A', '#F2B233', '#f2a624'].map((g) => tok(`text-[${g}]`)).concat([tok('text-secondary'), tok('text-gold')]);
const goldInline = ['rgb(201, 163, 77)', 'rgb(200, 169, 110)', 'rgb(213, 178, 93)', 'rgb(225, 191, 103)', 'rgb(242, 166, 36)'].map((c) => `[style^="color: ${c}"], [style*="; color: ${c}"]`);

// Light coloured text (300/400) → darker shade readable on white
const shade = { red: '#b91c1c', rose: '#be123c', pink: '#be185d', orange: '#c2410c', amber: '#b45309', yellow: '#a16207', lime: '#4d7c0f', green: '#15803d', emerald: '#047857', teal: '#0f766e', cyan: '#0e7490', sky: '#0369a1', blue: '#1d4ed8', indigo: '#4338ca', violet: '#6d28d9', purple: '#7e22ce', fuchsia: '#a21caf' };

let css = `/* ─────────────────────────────────────────────────────────────────────────
   Dashboard light theme — generated by gen_admin_css.js; edit the generator
   (scripts/gen-admin-theme.js) rather than this file. Scoped to .admin-shell (admin/layout.js), so the
   public site and the login page are unaffected. Matches the site identity:
   white surfaces, slate ink scale, deep gold for text, brand gold for fills.
   ───────────────────────────────────────────────────────────────────────── */

${S} {
  --a-canvas: #f8fafc;
  --a-surface: #ffffff;
  --a-line: #e2e8f0;
  color-scheme: light;
  background-color: var(--a-canvas);
  color: #334155;
}
${S} .min-h-screen[class*="bg-[var(--background)]"] { background-color: var(--a-canvas) !important; }

/* Dark surfaces → white cards/panels */
${S} :is(${darkCls.join(', ')}):not(${KEEP}),
${S} :is(${darkInline.join(', ')}):not(${KEEP}) {
  background: var(--a-surface) !important;
  background-color: var(--a-surface) !important;
}
/* Dark gradient panels → white */
${S} :is([class*="from-black"], [class*="from-[#0"], [class*="from-[#1"], [class*="from-slate-9"], [class*="from-slate-8"], [class*="from-gray-9"]):not(${KEEP}) {
  background-image: none !important;
  background-color: var(--a-surface) !important;
}
/* Translucent white "glass" → white surface; hover tint → canvas grey */
${S} [class*="bg-white/"]:not(${KEEP}),
${S} [style*="background: rgba(255, 255, 255, 0.0"]:not(${KEEP}) {
  background-color: var(--a-surface) !important;
  background-image: none !important;
  backdrop-filter: none !important;
}
${S} [class*="hover:bg-white/"]:hover:not(${KEEP}) { background-color: #f1f5f9 !important; }

/* Top bar, sidebar, bottom bar */
${S} header, ${S} aside, ${S} nav.fixed {
  background: var(--a-surface) !important;
  box-shadow: 0 1px 0 var(--a-line), 0 4px 16px -8px rgba(15, 23, 42, 0.08) !important;
}

/* Borders: white hairlines → slate line */
${S} [class*="border-white"]:not(${KEEP}) { border-color: var(--a-line) !important; }
${S} [style*="solid rgba(255, 255, 255"]:not(${KEEP}) { border-color: var(--a-line) !important; }
${S} :is(.divide-white\\/5, .divide-white\\/10, [class*="divide-white/"]) > * + * { border-color: var(--a-line) !important; }

/* Heavy black shadows → soft neutral */
${S} [class*="shadow-["][class*="rgba(0,0,0"]:not(${KEEP}) { box-shadow: 0 12px 32px -14px rgba(15, 23, 42, 0.18) !important; }

/* Ink scale for text-white tiers */
`;
for (const [color, list] of tiers) {
  css += `${S} :is(${list.map(tok).join(', ')}):not(${KEEP}) { color: ${color} !important; }\n`;
}
css += `${S} [class~="hover:text-white"]:hover:not(${KEEP}),
${S} .group:hover [class~="group-hover:text-white"]:not(${KEEP}) { color: #0f172a !important; }
${S} :is([class~="hover:text-white/70"], [class~="hover:text-white/60"], [class~="hover:text-white/50"]):hover:not(${KEEP}) { color: #334155 !important; }

/* Gold text → logo orange */
${S} :is(${goldText.join(', ')}):not(${KEEP}),
${S} :is(${goldInline.join(', ')}):not(${KEEP}) { color: #f2a624 !important; }
/* Gold fills keep brand gold with dark text */
${S} :is(${['#c8a96e', '#C9A34D', '#D5B25D', '#E1BF67'].map((g) => tok(`bg-[${g}]`)).join(', ')}) { color: #0f172a; }

/* Text on solid coloured fills (buttons, badges) stays white — listed once
   here instead of excluded in every rule; higher specificity wins. */
${S} :is(${solid})[class*="text-white"],
${S} :is(${solid}) [class*="text-white"] { color: #ffffff !important; }

/* Light status colours → readable shades on white */
`;
for (const [h, c] of Object.entries(shade)) {
  css += `${S} :is(${[200, 300, 400].map((n) => tok(`text-${h}-${n}`)).concat([200, 300, 400].flatMap((n) => [70, 75, 80, 85, 90].map((o) => tok(`text-${h}-${n}/${o}`)))).join(', ')}):not(${KEEP}) { color: ${c} !important; }\n`;
}
css += `
/* Inputs */
${S} :is(input, textarea, select):not([type="checkbox"]):not([type="radio"]):not([type="range"]):not([type="color"]):not(${KEEP}) {
  background-color: #ffffff !important;
  border-color: #cbd5e1 !important;
  color: #0f172a !important;
}
${S} :is(input, textarea, select):focus:not(${KEEP}) {
  border-color: #B8923A !important;
  box-shadow: 0 0 0 3px rgba(213, 178, 93, 0.18) !important;
  outline: none;
}
${S} :is(input, textarea)::placeholder { color: #94a3b8 !important; }
${S} option { background: #ffffff; color: #0f172a; }

/* Charts (recharts) */
${S} .recharts-cartesian-axis-tick-value, ${S} .recharts-text { fill: #64748b !important; }
${S} .recharts-cartesian-grid line, ${S} .recharts-cartesian-axis-line { stroke: var(--a-line) !important; }
${S} .recharts-default-tooltip {
  background: #ffffff !important;
  border: 1px solid var(--a-line) !important;
  border-radius: 10px;
  box-shadow: 0 12px 28px -12px rgba(15, 23, 42, 0.2);
  color: #334155 !important;
}
${S} .recharts-legend-item-text { color: #475569 !important; }

/* Scrollbars inside the dashboard */
${S} ::-webkit-scrollbar-track { background: var(--a-canvas); }
`;
fs.writeFileSync(OUT, css);
console.log('wrote', OUT, css.length, 'bytes');
